def _generate_conventions(profile: CodebaseProfile) -> list[str]:
    lines: list[str] = []
    lang = profile.primary_language

    if lang == "python":
        lines.append("- Follow PEP 8 style guidelines.")
        lines.append("- Use type hints for function signatures.")
        if "pydantic" in profile.frameworks:
            lines.append("- Use Pydantic models for data validation.")
        if "ruff" in (profile.lint_command or ""):
            lines.append("- Ruff is used for linting and formatting. Follow its rules.")
        if "pytest" in profile.test_frameworks:
            lines.append("- Tests use pytest. Place tests in the `tests/` directory.")
    elif lang in ("typescript", "javascript"):
        lines.append("- Use consistent import style (check existing code).")
        if "eslint" in (profile.lint_command or "") or any(
            "eslint" in f for f in profile.config_files
        ):
            lines.append("- ESLint is configured. Follow its rules.")
        if any("prettier" in f for f in profile.config_files):
            lines.append("- Prettier is used for formatting.")
        if "typescript" in profile.languages:
            lines.append("- Use TypeScript types; avoid `any`.")
    elif lang == "go":
        lines.append("- Follow standard Go conventions (gofmt, go vet).")
        lines.append("- Use table-driven tests.")
        lines.append("- Handle errors explicitly; do not ignore them.")
    elif lang == "rust":
        lines.append("- Follow Rust conventions (cargo fmt, clippy).")
        lines.append("- Prefer returning `Result` over panicking.")

    if not lines:
        lines.append("- Follow the existing code style found in the repository.")

    return lines


def _generate_framework_instructions(profile: CodebaseProfile) -> list[str]:
    lines: list[str] = []

    if "django" in profile.frameworks:
        lines.append("- Django project. Use the ORM for database operations.")
        lines.append("- Create/update migrations when modifying models (`python manage.py makemigrations`).")
        lines.append("- Follow Django's app-based architecture.")
    if "fastapi" in profile.frameworks:
        lines.append("- FastAPI project. Use async endpoints where possible.")
        lines.append("- Use Pydantic models for request/response schemas.")
        lines.append("- Use dependency injection for shared resources.")
    if "flask" in profile.frameworks:
        lines.append("- Flask project. Use blueprints for organizing routes.")
    if "react" in profile.frameworks:
        lines.append("- React project. Prefer functional components with hooks.")
        lines.append("- Keep components small and focused.")
    if "next" in profile.frameworks:
        lines.append("- Next.js project. Use the App Router pattern if `app/` directory exists.")
        lines.append("- Use Server Components by default; add 'use client' only when needed.")
    if "vue" in profile.frameworks:
        lines.append("- Vue project. Use Composition API with `<script setup>`.")
    if "express" in profile.frameworks:
        lines.append("- Express project. Use middleware for cross-cutting concerns.")
        lines.append("- Use error-handling middleware for consistent error responses.")
    if "sqlalchemy" in profile.frameworks:
        lines.append("- SQLAlchemy is used for database access. Use the session pattern.")

    return lines


def _build_observer_config(profile: CodebaseProfile) -> dict:
    """Configure observers based on detected tech stack."""
    observers: dict = {}

    # Process observer -- always useful
    observers["process"] = {"enabled": True}

    # Test watcher -- if we have tests
    if profile.test_command:
        observers["test_watcher"] = {
            "enabled": True,
            "command": profile.test_command,
        }

    # Log watcher -- if it's a server app
    if profile.api_app or profile.web_app:
        observers["log_watcher"] = {
            "enabled": True,
            "patterns": ["*.log", "logs/*.log"],
        }

    # Endpoint health -- if it's a web/API app
    if profile.dev_server_command:
        port = "3000" if profile.primary_language in ("typescript", "javascript") else "8000"
        observers["endpoint_health"] = {
            "enabled": True,
            "endpoints": [f"http://localhost:{port}/"],
        }

    return observers


def _build_hook_config(profile: CodebaseProfile) -> dict:
    """Configure hooks based on detected tooling."""
    hooks: dict = {}

    if profile.format_command:
        hooks["format"] = {
            "event": "post_turn",
            "command": profile.format_command,
        }

    if profile.type_check_command:
        hooks["type_check"] = {
            "event": "post_turn",
            "command": profile.type_check_command,
        }

    if profile.lint_command:
        hooks["lint"] = {
            "event": "post_turn",
            "command": profile.lint_command,
        }

    if profile.test_command:
        hooks["test"] = {
            "event": "post_turn",
            "command": profile.test_command,
        }

    return hooks


def _build_skills_config(profile: CodebaseProfile) -> list[str]:
    """Select default skills based on project type."""
    skills = ["coding_general"]

    if profile.test_command:
        skills.append("test_fixer")

    return skills


def _build_browser_flows(profile: CodebaseProfile) -> list[dict]:
    """Generate browser test flow stubs for web apps."""
    if not profile.web_app:
        return []

    port = "3000" if profile.primary_language in ("typescript", "javascript") else "8000"
    base_url = f"http://localhost:{port}"

    flows = [
        {
            "name": "homepage_loads",
            "url": base_url,
            "steps": [
                {"action": "wait_for", "selector": "body", "timeout": 10000},
            ],
            "assertions": [
                {"type": "element_visible", "selector": "body"},
                {"type": "no_console_errors"},
            ],
        },
    ]

    return flows
