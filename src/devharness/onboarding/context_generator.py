"""Context generator -- produces AGENTS.md and harness config from a CodebaseProfile."""

from __future__ import annotations

from devharness.onboarding.scanner import CodebaseProfile


def generate_agents_md(profile: CodebaseProfile) -> str:
    """Generate an AGENTS.md file tailored to the detected codebase."""
    sections: list[str] = []

    # Header
    sections.append("# AGENTS.md")
    sections.append("")
    sections.append("This file was auto-generated by `harness init`. Edit it to refine agent behavior.")
    sections.append("")

    # Project overview
    sections.append("## Project Overview")
    sections.append("")
    type_labels = []
    if profile.web_app:
        type_labels.append("web application")
    if profile.api_app:
        type_labels.append("API service")
    if profile.cli_app:
        type_labels.append("CLI tool")
    if profile.library:
        type_labels.append("library/package")
    if not type_labels:
        type_labels.append("software project")

    sections.append(f"- **Type:** {', '.join(type_labels)}")
    sections.append(f"- **Primary language:** {profile.primary_language}")
    if profile.frameworks:
        sections.append(f"- **Frameworks:** {', '.join(profile.frameworks)}")
    if profile.package_managers:
        sections.append(f"- **Package managers:** {', '.join(profile.package_managers)}")
    sections.append(f"- **Estimated size:** {profile.estimated_size}")
    sections.append("")

    # Directory structure
    if profile.directory_structure:
        sections.append("## Directory Structure")
        sections.append("")
        sections.append("```")
        for dirname, files in sorted(profile.directory_structure.items()):
            sections.append(f"{dirname}/")
            for f in files[:5]:
                sections.append(f"  {f}")
            if len(files) > 5:
                sections.append(f"  ... ({len(files) - 5} more)")
        sections.append("```")
        sections.append("")

    # Commands
    sections.append("## Commands")
    sections.append("")
    commands = [
        ("Test", profile.test_command),
        ("Lint", profile.lint_command),
        ("Format", profile.format_command),
        ("Build", profile.build_command),
        ("Type check", profile.type_check_command),
        ("Dev server", profile.dev_server_command),
    ]
    for label, cmd in commands:
        if cmd:
            sections.append(f"- **{label}:** `{cmd}`")
    if not any(cmd for _, cmd in commands):
        sections.append("_No commands detected. Add them manually._")
    sections.append("")

    # Entry points
    if profile.entry_points:
        sections.append("## Entry Points")
        sections.append("")
        for ep in profile.entry_points:
            sections.append(f"- `{ep}`")
        sections.append("")

    # Conventions
    sections.append("## Conventions")
    sections.append("")
    sections.extend(_generate_conventions(profile))
    sections.append("")

    # Framework-specific instructions
    fw_instructions = _generate_framework_instructions(profile)
    if fw_instructions:
        sections.append("## Framework Notes")
        sections.append("")
        sections.extend(fw_instructions)
        sections.append("")

    # CI/CD
    if profile.has_ci:
        sections.append("## CI/CD")
        sections.append("")
        sections.append(f"- CI system: {profile.ci_system}")
        sections.append("- Ensure all changes pass CI before considering work complete.")
        sections.append("")

    # Agent rules
    sections.append("## Agent Rules")
    sections.append("")
    sections.append("1. Read existing code before modifying it.")
    sections.append("2. Run tests after every change.")
    sections.append("3. Follow the existing code style and conventions.")
    sections.append("4. Do not modify files outside the workspace root.")
    sections.append("5. When uncertain, ask rather than guess.")
    if profile.lint_command:
        sections.append(f"6. Run `{profile.lint_command}` before finishing work.")
    if profile.format_command:
        sections.append(
            f"{'7' if profile.lint_command else '6'}. Run `{profile.format_command}` "
            "to format code before committing."
        )
    sections.append("")

    return "\n".join(sections)


def generate_harness_config(profile: CodebaseProfile) -> dict:
    """Generate harness configuration dict from the profile.

    Returns a dict suitable for storing in the harness DB as project settings.
    """
    config: dict = {
        "profile": {
            "primary_language": profile.primary_language,
            "languages": profile.languages,
            "frameworks": profile.frameworks,
            "package_managers": profile.package_managers,
            "estimated_size": profile.estimated_size,
            "web_app": profile.web_app,
            "api_app": profile.api_app,
            "cli_app": profile.cli_app,
            "library": profile.library,
        },
        "commands": {
            "test": profile.test_command,
            "lint": profile.lint_command,
            "format": profile.format_command,
            "build": profile.build_command,
            "type_check": profile.type_check_command,
            "dev_server": profile.dev_server_command,
        },
        "observers": _build_observer_config(profile),
        "hooks": _build_hook_config(profile),
        "skills": _build_skills_config(profile),
        "browser_test_flows": _build_browser_flows(profile),
    }
    return config


